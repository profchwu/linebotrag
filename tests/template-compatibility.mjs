import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const book=JSON.parse(fs.readFileSync(new URL('./template-extracted.json',import.meta.url),'utf8'));
const elements=new Map();
const document={querySelector(k){if(!elements.has(k))elements.set(k,{innerHTML:'',textContent:'',value:'',addEventListener(){},classList:{add(){},remove(){}}});return elements.get(k)},querySelectorAll(){return []},addEventListener(){}};
const app={document,window:{addEventListener(){}},location:{hash:''},localStorage:{getItem(){return null},setItem(){}},URL,Blob,structuredClone,console,setTimeout,clearTimeout};
vm.createContext(app);
for(const file of ['app.js','connections.js','wizard.js'])vm.runInContext(fs.readFileSync(new URL('../dist/'+file,import.meta.url),'utf8'),app);
const code=vm.runInContext('generateGas()',app);
const props=new Map([['SPREADSHEET_ID','template-test']]);
const sheets=Object.entries(book).map(([name,rows],i)=>({getName:()=>name,getSheetId:()=>i+1,getDataRange:()=>({getDisplayValues:()=>structuredClone(rows)})}));
const requests=[];
const gas={PropertiesService:{getScriptProperties:()=>({getProperty:k=>props.get(k),setProperty:(k,v)=>props.set(k,v)})},SpreadsheetApp:{openById:()=>({getSheets:()=>sheets,getSheetByName:n=>sheets.find(s=>s.getName()===n)})},UrlFetchApp:{fetch(url,options){requests.push({url,options});return {getResponseCode:()=>200,getContentText:()=>JSON.stringify({answer:'模擬 RAG 回覆',candidates:[{content:{parts:[{text:'模擬 AI 回覆'}]}}]})}}}};
vm.createContext(gas);
vm.runInContext(code,gas);
const run=x=>vm.runInContext(x,gas);
assert.equal(run('setupConfigSheet().name'),'Setting');
assert.equal(props.get('CONFIG_SHEET_ID'),'2');
assert.equal(run('loadConfig_().AI_ROLE'),book.Setting.find(r=>r[0]==='AI_ROLE')[1]);
assert.equal(run('testSheetConnection().rowCount'),0);
assert.equal(run('loadRules_().length'),2);
assert.match(run('handleTextMessage_("你好")'),/歡迎/);
assert.equal(run('handleTextMessage_("官網")'),book.Setting.find(r=>r[0]==='NO_ANSWER_MESSAGE')[1]);
book.Keywords[4][1]='TRUE';
assert.match(run('handleTextMessage_("官網")'),/https:\/\/example.com/);
book.Keywords.push(['rule-new','TRUE','新規則','exact','text','新增後立即可讀','']);
assert.equal(run('handleTextMessage_("新規則")'),'新增後立即可讀');
assert.equal(requests.length,0);
book.Setting.find(r=>r[0]==='AI_ENABLED')[1]='true';
book.Setting.find(r=>r[0]==='AI_MODEL')[1]='test-model';
props.set('AI_API_KEY','test-only-key');
assert.equal(run('handleTextMessage_("未命中規則")'),'模擬 AI 回覆');
assert.ok(JSON.parse(requests.at(-1).options.payload).contents[0].parts[0].text.includes(book.Setting.find(r=>r[0]==='AI_ROLE')[1]));
book.Setting.find(r=>r[0]==='RAG_ENABLED')[1]='true';
assert.throws(()=>run('handleTextMessage_("未命中規則")'),/RAG/);
props.set('RAG_ENDPOINT','https://example.com/rag');props.set('RAG_TOKEN','test-only-token');
assert.equal(run('handleTextMessage_("未命中規則")'),'模擬 RAG 回覆');
assert.equal(JSON.parse(requests.at(-1).options.payload).role,book.Setting.find(r=>r[0]==='AI_ROLE')[1]);
console.log('PASS: actual template values used by generated GAS: Setting binding, Data headers, Keywords text/URL/additions, AI Prompt and external RAG request. Cloud services mocked.');
